#: Prefix shared by most retired names. Used to catch the per-group
#: variables that are built at runtime and any variable that a launch
#: script grew after the table above was written. Names outside the prefix
#: are caught by their table entry alone -- see ``check_retired_env_vars``.
RETIRED_PREFIX = "SGLANG_HTCCL"


class RetiredEnvVarError(RuntimeError):
    """A retired ``SGLANG_HTCCL*`` variable is set in the environment."""


def successor(name: str) -> str:
    """The current name for a retired one. Falls back to the prefix swap."""
    return RETIRED_ENV_VARS.get(name) or name.replace(
        RETIRED_PREFIX, "SGLANG_BARLINK", 1
    )


def check_retired_env_vars(environ=None) -> None:
    """Raise if any retired variable is set. Called at import time below.

    Not a warning: see the module docstring. Every retired variable that is
    set is reported in one message, so a stale script is fixed in one pass
    rather than one failure at a time.
    """
    env = os.environ if environ is None else environ
    # Two ways in: the prefix (catches names built at runtime and names a
    # launch script grew after this table was written) and an exact table
    # entry (catches retired names that never carried the prefix).
    found = sorted(
        n for n in env if n.startswith(RETIRED_PREFIX) or n in RETIRED_ENV_VARS
    )
    if not found:
        return
    lines = "\n".join(f"  {n} -> {successor(n)}" for n in found)
    raise RetiredEnvVarError(
        "the collective transport formerly called HTCCL is now called "
        "barlink (task #358), and its environment surface was renamed with "
        "it. These variables are set but nothing reads them any more:\n"
        f"{lines}\n"
        "Rename them in the launch script. There is no alias and no "
        "fallback: an ignored transport variable would silently change "
        "what a run measures."
    )


check_retired_env_vars()
