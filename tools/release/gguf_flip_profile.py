#!/usr/bin/env python3
"""NF-GGUF Stufe B (14.10.2026): ONE bootable, flat rig profile for the GGUF FLIP form, built on the NF Dauerstand profile.

WHY.  The Dauerstand (``nf-int4-h6-abl-xc-w3sp-mlr-hl-vw``, image int24f8) is a rig-spelled FLAT profile that is NOT in
``tools/release/profconv/`` (that chain stops at ``nf-int4-h6-abl``), so ``flat_profile.py`` cannot derive a GGUF flip
profile from it.  ``profconv/nf-gguf.env`` applies the GGUF changes to ``nf.env`` (the h91bb4 release form), which lacks
everything the Dauerstand added since (x-curves switch, W3-spill, mamba last resort, lanes/void-pass envs, the ``-vw``
vision placement ...).  This tool applies the SAME changes (``gguf_flip_overlay.env``, every line named in its header) to
the Dauerstand itself: ``<Dauerstand text verbatim> + <overlay>``.  Nothing of the Dauerstand file is edited; its sha256
is in the header, so the generated file says which Dauerstand it was built on and a later Dauerstand change is detected
(``--check``), not silently inherited.

WHAT.  ``gguf_flip_profile.py [--base FILE] [--check]`` writes ``docker/profiles_release/nf-gguf-flip-int24f8.env``:
header (sources + sha256) + base + overlay.  ``--check`` writes nothing and exits 1 when the committed file differs.
The base file is outside the repo (``/spinning/gpu-arb/docker/profiles`` on the rig); a box without it cannot regenerate
(the committed file then stands, the test that compares them skips with the reason).

Usage:  python3 tools/release/gguf_flip_profile.py [--check] [--base FILE] [--dst DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
NAME = "nf-gguf-flip-int24f8"
DEFAULT_BASE = "/spinning/gpu-arb/docker/profiles/nf-int4-h6-abl-xc-w3sp-mlr-hl-vw.env"
OVERLAY = os.path.join(HERE, "gguf_flip_overlay.env")
DEFAULT_DST = os.path.join(REPO, "docker", "profiles_release")

BEGIN_BASE = "# >>> BASE (Dauerstand, verbatim) >>>"
END_BASE = "# <<< END BASE <<<"
BEGIN_OVERLAY = "# >>> OVERLAY (tools/release/gguf_flip_overlay.env, verbatim) >>>"
END_OVERLAY = "# <<< END OVERLAY <<<"


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build(base_text: str, base_name: str, overlay_text: str) -> str:
    """The flat profile text for ``base_text`` + ``overlay_text`` (both verbatim, newline-terminated)."""
    if not base_text.endswith("\n"):
        base_text += "\n"
    if not overlay_text.endswith("\n"):
        overlay_text += "\n"
    header = (
        "# shellcheck shell=bash\n"
        f"# GENERATED by tools/release/gguf_flip_profile.py -- DO NOT EDIT; change gguf_flip_overlay.env and regenerate.\n"
        f"# GGUF flip profile {NAME} (NF-GGUF Stufe B, 14.10.2026): the NF Dauerstand profile + the GGUF flip overlay, one flat file\n"
        "# (PROFILE_MOUNT=1 carries ONE file). Sources:\n"
        f"#   base     {base_name}  sha256 {_sha(base_text)}\n"
        f"#   overlay  tools/release/gguf_flip_overlay.env  sha256 {_sha(overlay_text)}\n"
        f"# Install: copy to the rig's docker/profiles/{NAME}.env (PROF={NAME}; nf_dauer_loop_v2.sh sets ALLOW_EXPERIMENTAL=1).\n"
    )
    return (
        header
        + BEGIN_BASE + "\n" + base_text + END_BASE + "\n"
        + BEGIN_OVERLAY + "\n" + overlay_text + END_OVERLAY + "\n"
    )


def split(text: str):
    """``(base_text, overlay_text)`` of a generated file (the inverse of :func:`build`'s body), or ``None``."""
    try:
        a = text.index(BEGIN_BASE + "\n") + len(BEGIN_BASE) + 1
        b = text.index(END_BASE + "\n")
        c = text.index(BEGIN_OVERLAY + "\n") + len(BEGIN_OVERLAY) + 1
        d = text.index(END_OVERLAY + "\n")
    except ValueError:
        return None
    return text[a:b], text[c:d]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--base", default=DEFAULT_BASE)
    ap.add_argument("--dst", default=DEFAULT_DST)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the committed file differs")
    a = ap.parse_args(argv)
    if not os.path.isfile(a.base):
        print("NO BASE", a.base)
        return 2
    text = build(_read(a.base), os.path.basename(a.base), _read(OVERLAY))
    dst = os.path.join(a.dst, NAME + ".env")
    old = _read(dst) if os.path.exists(dst) else None
    if old == text:
        print("same   ", dst)
        return 0
    if a.check:
        print("DIFFERS", dst, "(missing)" if old is None else "")
        return 1
    os.makedirs(a.dst, exist_ok=True)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("written", dst, "(was missing)" if old is None else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
