#!/usr/bin/env python3
"""G13 (NF-GGUF, 12.10.2026): one BOOTABLE, FLAT rig profile file from a profconv/ source chain.

WHY.  The stage-A boot of ``nf-gguf-d`` could not start from the tree as it stood (Metall-Bericht G12, section 3.1):

  a. ``host_acceptance.sh`` (PROFILE_MOUNT=1) binds exactly ONE profile file into the container, but ``nf-gguf-d.env``
     ``source``s ``nf-gguf.env``, which ``source``s ``nf.env`` from ``$(dirname BASH_SOURCE)``.  Next to the mounted file
     the image carried the 25.09. PLACEHOLDER ``nf-gguf.env`` (PROFILE_PLACEHOLDER=1) and an old ``nf.env``;
  b. ``tools/release/profconv/`` is the fLLiper spelling (``FLLIPER_*``, ``--pdflip-*``); the rig and
     ``acc_nf_m1_donly.sh`` (which refuses every ``FLLIPER_`` in a profile file, comments included) speak
     ``SGLANG_*`` / ``--weg2-*``;
  c. ``PROFILE_REQUIRED_PATHS`` named ``$NF_STORE_DIR`` (``/mnt/nf-experts/gguf``), but in the container
     ``/mnt/nf-experts`` is a fresh tmpfs and ``preflight_model`` (entrypoint.sh:711, checks the paths) runs BEFORE
     ``preflight_state`` (:712, creates the directories) -> ``refuse MODEL``.  (c) is fixed in the SOURCE profile
     ``profconv/nf-gguf-d.env`` (the store path is created, not required; no other profile lists it), (a) and (b) here.

WHAT.  ``flat_profile.py nf-gguf-d`` reads ``profconv/nf-gguf-d.env``, inlines every
``source "$(dirname "${BASH_SOURCE[0]}")/X.env"`` line with X (recursively, in place, so the later file still overrides
the earlier one exactly as ``source`` did), then maps the spelling back to the rig's:

    FLLIPER_ -> SGLANG_     PDFLIP -> WEG2     pdflip -> weg2

(the inverse of ``rename_to_flliper.rewrite_all`` on a profile text; byte-exact on ``nf.env`` against the rig's
``profiles_release/nf.env``, pinned by a test where that file is mounted).  The result is written to
``docker/profiles_release/<name>.env`` with a header that names the sources and their sha256.  It carries no ``source``
line and no ``FLLIPER_``.

``--check`` writes nothing and exits 1 when the committed flat file differs from what the sources give.  The test
``test_flat_profile_g13_1012.py`` sources the flat file and the source chain (rig spelling) in bash and compares every
``PROFILE_*`` / ``NF_*`` variable and array, so the flat file cannot drift from the chain it came from.

Usage:  python3 tools/release/flat_profile.py nf-gguf-d [--check] [--src DIR] [--dst DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from typing import List, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_SRC = os.path.join(HERE, "profconv")
DEFAULT_DST = os.path.join(REPO, "docker", "profiles_release")

#: the one way the chain links itself (nf-gguf-d.env, nf-gguf.env)
_SOURCE_LINE = re.compile(
    r'^source\s+"\$\(dirname\s+"\$\{BASH_SOURCE\[0\]\}"\)/(?P<name>[A-Za-z0-9_.\-]+\.env)"(?P<tail>\s*(#.*)?)$'
)


def to_rig_spelling(text: str) -> str:
    """fLLiper profile text -> the rig's spelling (inverse of ``rename_to_flliper.rewrite_all`` for a profile)."""
    text = text.replace("FLLIPER_", "SGLANG_")
    text = text.replace("PDFLIP", "WEG2")
    return text.replace("pdflip", "weg2")


def _read(src: str, name: str) -> str:
    with open(os.path.join(src, name), encoding="utf-8") as fh:
        return fh.read()


def inline_chain(src: str, name: str, _stack: Tuple[str, ...] = ()) -> Tuple[List[str], List[str]]:
    """``(lines, chain)``: the profile's lines with every sibling ``source`` replaced by that sibling's lines."""
    if name in _stack:
        raise ValueError(f"profile source cycle: {' -> '.join(_stack + (name,))}")
    out: List[str] = []
    chain = [name]
    for line in _read(src, name).splitlines():
        m = _SOURCE_LINE.match(line)
        if m is None:
            if "BASH_SOURCE" in line and not line.lstrip().startswith("#"):
                raise ValueError(
                    f"{name}: a BASH_SOURCE use that is not a sibling source line cannot be flattened: {line!r}"
                )
            out.append(line)
            continue
        sub = m.group("name")
        sub_lines, sub_chain = inline_chain(src, sub, _stack + (name,))
        chain += [c for c in sub_chain if c not in chain]
        out.append(f"# >>> inlined from {sub} (was: source ... /{sub}) >>>")
        out.extend(sub_lines)
        out.append(f"# <<< end of {sub} <<<")
    return out, chain


def flatten(src: str, name: str) -> str:
    """The flat rig-spelled text of profile ``name`` (``name`` without ``.env``)."""
    lines, chain = inline_chain(src, name + ".env")
    digests = "\n".join(
        f"#   {c:<18} sha256 {hashlib.sha256(_read(src, c).encode('utf-8')).hexdigest()}" for c in chain
    )
    header = (
        "# shellcheck shell=bash\n"
        f"# GENERATED by tools/release/flat_profile.py {name} -- DO NOT EDIT; change the source profile and regenerate.\n"
        "# One flat, bootable rig profile (G13, 12.10.2026): the profconv/ source chain below, inlined in source order and\n"
        "# in the rig's spelling (SGLANG_*, --weg2-*), so PROFILE_MOUNT=1 (one file) carries the whole profile and\n"
        "# acc_nf_m1_donly.sh finds none of the fLLiper names it refuses. Sources (fLLiper spelling, tools/release/profconv/), later overrides earlier:\n"
        f"{digests}\n"
        f"# Install: copy to the rig's docker/profiles/{name}.env (PROF={name}).\n"
    )
    body = "\n".join(lines)
    if not body.endswith("\n"):
        body += "\n"
    # the spelling map is applied to the BODY only: the header names the old spelling on purpose
    return header + to_rig_spelling(body)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("profile", help="profile name without .env, e.g. nf-gguf-d")
    ap.add_argument("--src", default=DEFAULT_SRC)
    ap.add_argument("--dst", default=DEFAULT_DST)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the committed flat file differs")
    a = ap.parse_args(argv)
    text = flatten(a.src, a.profile)
    dst = os.path.join(a.dst, a.profile + ".env")
    old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else None
    if old == text:
        print("same   ", dst)
        return 0
    if a.check:
        print("DIFFERS", dst, "(missing)" if old is None else "")
        return 1
    os.makedirs(a.dst, exist_ok=True)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("written", dst, "(was missing)" if old is None else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
