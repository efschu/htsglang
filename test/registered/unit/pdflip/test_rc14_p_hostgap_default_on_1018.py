"""rc14 (NF 1018): the #PGAP instrument (--p-hostgap) is ON by default.

Planer order for the rc14 NF boot: the P pauses (PP0 duty 57 % in the rc12
busy runs, card idle per chunk, S43 A metal check ``#PGAP ... overlap=1``) are
the class this boot must measure, and the boot profile is regenerated by
profconv on every boot from a source profile that names neither
``--p-hostgap`` nor ``--no-p-hostgap`` -- so the launcher default is the one
place the switch reaches the boot. The instrument harvests its timing events
with ``Event.query()`` (no host sync) and changes no decision; the off arm
``--no-p-hostgap`` keeps the old env byte-identical.
"""

import os

os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")

from flliper.srt.managers import pdflip_p_overlap as pov
from flliper.srt.pdflip import launcher as L

BASE = ["--tree", "/t", "--tag", "t"]


def test_hostgap_is_on_without_a_flag():
    assert L.build_parser().parse_args(BASE).p_hostgap is True


def test_no_twin_turns_it_off_and_the_flag_keeps_it_on():
    assert L.build_parser().parse_args(BASE + ["--no-p-hostgap"]).p_hostgap is False
    assert L.build_parser().parse_args(BASE + ["--p-hostgap"]).p_hostgap is True
    # last one wins, like every on/off pair of the launcher
    assert L.build_parser().parse_args(BASE + ["--no-p-hostgap", "--p-hostgap"]).p_hostgap is True


def test_the_default_puts_the_variable_into_group_p_env_beside_the_overlap():
    ns = L.build_parser().parse_args(BASE)
    env = L.p_host_overlap_env(ns.p_host_overlap, ns.p_hostgap)
    assert env.get(pov.P_HOSTGAP_ENV) == "1"
    assert env.get(pov.P_HOST_OVERLAP_ENV) == "1"
    lines = L.p_host_overlap_lines(ns.p_host_overlap, ns.p_hostgap)
    assert any(line.startswith("PDFLIP P-HOSTGAP: on") for line in lines)


def test_the_off_arm_drops_only_the_instrument():
    ns = L.build_parser().parse_args(BASE + ["--no-p-hostgap"])
    env = L.p_host_overlap_env(ns.p_host_overlap, ns.p_hostgap)
    assert pov.P_HOSTGAP_ENV not in env
    assert env.get(pov.P_HOST_OVERLAP_ENV) == "1"
    assert not any("P-HOSTGAP" in line for line in L.p_host_overlap_lines(ns.p_host_overlap, ns.p_hostgap))


def test_the_runtime_reads_the_name_the_launcher_sets():
    assert L.p_host_overlap_env(False, True) == {"FLLIPER_PDFLIP_P_HOSTGAP": "1"}
    old = os.environ.get(pov.P_HOSTGAP_ENV)
    try:
        os.environ[pov.P_HOSTGAP_ENV] = "1"
        assert pov.hostgap_on() is True
        os.environ.pop(pov.P_HOSTGAP_ENV)
        assert pov.hostgap_on() is False
    finally:
        if old is not None:
            os.environ[pov.P_HOSTGAP_ENV] = old
